PX = 100
UPM = 1000


def glyph_name(ch):
    return "space" if ch == " " else f"uni{ord(ch):04X}"


def build(out_path):
    order = [".notdef"] + [glyph_name(c) for c in G]
    fb = FontBuilder(UPM, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap({ord(c): glyph_name(c) for c in G})
    glyphs, metrics = {}, {}

    pen = TTGlyphPen(None)
    glyphs[".notdef"] = pen.glyph()
    metrics[".notdef"] = (4 * PX, 0)

    for ch, rows in G.items():
        pen = TTGlyphPen(None)
        width = max(len(r) for r in rows)
        for ri, row in enumerate(rows):
            top = (7 - ri) * PX  # row 0 top at 700
            x = 0
            while x < len(row):
                if row[x] == "#":
                    start = x
                    while x < len(row) and row[x] == "#":
                        x += 1
                    x0, x1 = start * PX, x * PX
                    y0, y1 = top - PX, top
                    pen.moveTo((x0, y0))
                    pen.lineTo((x0, y1))
                    pen.lineTo((x1, y1))
                    pen.lineTo((x1, y0))
                    pen.closePath()
                else:
                    x += 1
        glyphs[glyph_name(ch)] = pen.glyph()
        metrics[glyph_name(ch)] = ((width + 1) * PX, 0)

    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=800, descent=-200)
    fb.setupNameTable({"familyName": "tuftpix", "styleName": "Regular",
                       "copyright": "catnet, made for Tuft"})
    fb.setupOS2(sTypoAscender=800, sTypoDescender=-200, sTypoLineGap=0,
                usWinAscent=800, usWinDescent=200)
    fb.setupPost()
    fb.font.flavor = "woff"
    fb.save(out_path)
    return os.path.getsize(out_path)


